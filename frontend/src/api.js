// TODO(backend): POST /api/sessions/:id/answers
// Body: { cardId, chosenIndex } (multiple choice) or { cardId, selfGrade: 'got'|'missed' } (flashcard),
//       plus { mode, timeTakenMs } for the answer log.
// → { correct, correctIndex, correctOption, explanation, sourceSnippet, sourcePage,
//     xp, reason, parts, combo, masteryBefore, masteryAfter, leveledUp,
//     card, user: { xp, streak }, activity, deck }
//
// Cards generated by Flask (a live PDF quiz) are graded by Flask, all at once (the MVP flow):
// each pick is only saved ({ deferred: true }; picking again replaces it), and finishSession()
// sends every pick in one POST /api/quizzes/<quizId>/submit. Options keep Flask's order,
// because Flask grades by option index.
export async function submitAnswer(sessionId, { cardId, chosenIndex = null, selfGrade = null }) {
  const target = server.flaskTarget(sessionId, cardId)
  if (!target) return call(120, () => server.submitAnswer(sessionId, { cardId, chosenIndex, selfGrade }))

  if (!isLive()) {
    throw new Error('This deck is checked by the StudyQuest server. Turn off Demo mode in Settings to play it.')
  }
  return server.submitAnswer(sessionId, { cardId, chosenIndex, deferred: true })
}

// Submit the live quiz: one POST /submit per Flask quiz in the session (normally exactly one),
// then apply the verdicts (XP, schedule) as if each was graded on the spot.
// → { graded: [{ cardId, chosenIndex, correct, correctIndex, explanation, sourcePage, sourceSnippet, … }],
//     quizzes: [{ quizId, score, total, answers }] }
// If the request fails, nothing is applied and the saved picks stay, so it can simply be retried.
// Flask needs every question answered, so a half-finished quiz can't be submitted.
export async function finishSession(sessionId) {
  const graded = []
  const quizzes = []
  for (const { quizId, answers } of server.deferredAnswers(sessionId)) {
    const result = await flask.submitQuiz(quizId, answers)
    // Flask saves the first submission and returns it (with its `answers`) on every retry:
    // show what was saved, not what this browser sent this time.
    const saved = result.answers && typeof result.answers === 'object' ? result.answers : answers
    quizzes.push({ quizId, score: result.score, total: result.total, answers: saved })
    graded.push(...server.applySubmitResults(sessionId, quizId, result.results ?? [], saved))
  }
  return { graded, quizzes }
}

// A saved result, for #/results/<quizId>. Read-only: it never submits again or awards XP.
// GET /api/quizzes/<id>/result gives the grading (+ the student's answers); the question text and
// choices come from GET /api/quizzes/<id>, or from this account's copy of the deck.
// → { quizId, score, total, questions: [{ id, text, choices, chosen, correct, correctIndex,
//     explanation, sourcePage, sourceSnippet }] }
export async function getSavedResult(quizId) {
  if (!isLive()) throw new Error('Saved results come from the StudyQuest server. Turn off Demo mode in Settings to see them.')
  let result
  try {
    result = await flask.getResult(quizId)
  } catch (error) {
    if (error.status === flask.ROUTE_MISSING) {
      throw new Error('This server can’t load saved results yet. Your score showed when you submitted; saved results arrive with the next backend update.')
    }
    if (error.status === 404) throw new Error('There’s no saved result for this quiz. It may belong to another account, or it hasn’t been submitted yet.')
    throw error
  }
  const quiz = await flask.getQuiz(quizId).catch(() => null)
  const local = server.flaskQuizQuestions(quizId)
  const questionFor = (id) =>
    quiz?.questions?.find((q) => String(q.id) === String(id)) ?? local.find((q) => String(q.id) === String(id))
  return {
    quizId,
    score: result.score,
    total: result.total,
    deckId: local.length ? local[0].deckId : null,
    questions: (result.results ?? []).map((r) => {
      const q = questionFor(r.id)
      const chosen = result.answers?.[String(r.id)]
      return {
        id: r.id,
        text: q?.text ?? `Question ${r.id}`,
        choices: q?.choices ?? [],
        chosen: Number.isInteger(chosen) ? chosen : null,
        correct: Boolean(r.correct),
        correctIndex: Number.isInteger(r.correct_answer) ? r.correct_answer : null,
        explanation: r.explanation ?? null,
        sourcePage: r.sourcePage ?? null,
        sourceSnippet: r.sourceSnippet ?? null,
      }
    }),
  }
}

