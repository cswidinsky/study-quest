// TODO(backend): POST /api/sessions/:id/answers
// Body: { cardId, chosenIndex } (multiple choice) or { cardId, selfGrade: 'got'|'missed' } (flashcard),
//       plus { mode, timeTakenMs } for the answer log.
// → { correct, correctIndex, correctOption, explanation, sourceSnippet, sourcePage,
//     xp, reason, parts, combo, masteryBefore, masteryAfter, leveledUp,
//     card, user: { xp, streak }, activity, deck }
//
// Cards generated by Flask are graded by Flask:
//   1. POST /api/quizzes/<quizId>/answer { questionId, choice } (per-answer endpoint), and the
//      verdict is applied straight away (feedback, combos, XP).
//   2. If the server doesn't have that endpoint yet, the pick is kept ({ deferred: true }) and
//      everything is sent with POST /submit when the quiz ends (finishSession).
export async function submitAnswer(sessionId, { cardId, chosenIndex = null, selfGrade = null }) {
  const target = server.flaskTarget(sessionId, cardId)
  if (!target) return call(120, () => server.submitAnswer(sessionId, { cardId, chosenIndex, selfGrade }))

  if (!isLive()) {
    throw new Error('This deck is checked by the StudyQuest server. Turn on “Use the StudyQuest server” in Settings.')
  }
  if (perAnswer !== false) {
    const verdict = await flask.answerQuestion(target.quizId, target.questionId, chosenIndex)
    if (verdict) {
      perAnswer = true
      return server.submitAnswer(sessionId, { cardId, chosenIndex, verdict })
    }
    perAnswer = false
  }
  return server.submitAnswer(sessionId, { cardId, chosenIndex, deferred: true })
}

// When a quiz ends: send any picks that are still waiting to Flask (POST /api/quizzes/<id>/submit)
// and apply the results. Returns the graded answers in quiz order (empty if nothing was waiting).
// Flask needs every question answered, so ending a quiz early can't be graded this way.
export async function finishSession(sessionId) {
  const graded = []
  for (const { quizId, answers } of server.deferredAnswers(sessionId)) {
    const result = await flask.submitQuiz(quizId, answers)
    graded.push(...server.applySubmitResults(sessionId, quizId, result.results ?? []))
  }
  return graded
}

