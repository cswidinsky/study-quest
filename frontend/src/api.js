export const isLive = () => getApiMode() === 'live'

// Is Flask up? (Settings shows this.)
export const checkServer = () => flask.health()

// Does Flask have the per-answer endpoint? Unknown until the first try, re-checked each session.
let perAnswer = null

const wait = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

// Simulates a network round trip to the mock server.
async function call(ms, handler) {
  await wait(ms)
  return handler()
}

